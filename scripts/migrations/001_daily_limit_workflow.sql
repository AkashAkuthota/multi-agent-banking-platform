BEGIN;

CREATE TABLE daily_account_limits (
    account_id BIGINT PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    daily_limit NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_daily_account_limits_policy_range
        CHECK (daily_limit >= 10000.00 AND daily_limit <= 50000.00)
);

INSERT INTO daily_account_limits (account_id, daily_limit, currency)
SELECT id, 10000.00, currency
FROM accounts;

CREATE TABLE daily_limit_change_requests (
    request_id UUID PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    account_ref VARCHAR(20) NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id),
    previous_limit NUMERIC(15, 2) NOT NULL,
    requested_limit NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT uq_daily_limit_requests_customer_idempotency
        UNIQUE (customer_id, idempotency_key),
    CONSTRAINT ck_daily_limit_requests_policy_range
        CHECK (requested_limit >= 10000.00 AND requested_limit <= 50000.00),
    CONSTRAINT ck_daily_limit_requests_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED'))
);

CREATE UNIQUE INDEX uq_daily_limit_requests_pending_account
    ON daily_limit_change_requests (account_id)
    WHERE status = 'PENDING';

CREATE INDEX ix_daily_limit_requests_customer_created
    ON daily_limit_change_requests (customer_id, created_at DESC);

CREATE TABLE daily_limit_audit_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL
        REFERENCES daily_limit_change_requests(request_id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    event_type VARCHAR(20) NOT NULL,
    previous_limit NUMERIC(15, 2) NOT NULL,
    requested_limit NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_daily_limit_audit_events_type
        CHECK (event_type IN ('PROPOSED', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED'))
);

CREATE INDEX ix_daily_limit_audit_request_time
    ON daily_limit_audit_events (request_id, occurred_at);

COMMIT;
