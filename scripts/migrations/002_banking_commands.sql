BEGIN;

CREATE TABLE transfer_requests (
    request_id UUID PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    source_account_ref VARCHAR(20) NOT NULL,
    source_account_id BIGINT NOT NULL REFERENCES accounts(id),
    destination_account_ref VARCHAR(20) NOT NULL,
    destination_account_id BIGINT NOT NULL REFERENCES accounts(id),
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    source_transaction_id VARCHAR(30) UNIQUE,
    destination_transaction_id VARCHAR(30) UNIQUE,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    CONSTRAINT ck_transfer_requests_amount_range
        CHECK (amount > 0 AND amount <= 50000.00),
    CONSTRAINT ck_transfer_requests_distinct_accounts
        CHECK (source_account_id <> destination_account_id),
    CONSTRAINT ck_transfer_requests_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED')),
    CONSTRAINT uq_transfer_requests_customer_idempotency
        UNIQUE (customer_id, idempotency_key)
);

CREATE UNIQUE INDEX uq_transfer_requests_pending_source
    ON transfer_requests (source_account_id)
    WHERE status = 'PENDING';

CREATE INDEX ix_transfer_requests_customer_created
    ON transfer_requests (customer_id, created_at DESC);

CREATE TABLE transfer_audit_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL
        REFERENCES transfer_requests(request_id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    event_type VARCHAR(20) NOT NULL,
    source_account_ref VARCHAR(20) NOT NULL,
    destination_account_ref VARCHAR(20) NOT NULL,
    amount NUMERIC(15, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_transfer_audit_events_type
        CHECK (event_type IN ('PROPOSED', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED'))
);

CREATE INDEX ix_transfer_audit_request_time
    ON transfer_audit_events (request_id, occurred_at);

CREATE TABLE service_request_proposals (
    request_id UUID PRIMARY KEY,
    idempotency_key VARCHAR(128) NOT NULL,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    request_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    confirmed_at TIMESTAMPTZ,
    created_service_request_id VARCHAR(30) UNIQUE
        REFERENCES service_requests(request_id),
    CONSTRAINT ck_service_request_proposals_type
        CHECK (request_type IN ('STATEMENT', 'CHEQUE_BOOK', 'CARD_REPLACEMENT')),
    CONSTRAINT ck_service_request_proposals_status
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED')),
    CONSTRAINT uq_service_request_proposals_customer_idempotency
        UNIQUE (customer_id, idempotency_key)
);

CREATE INDEX ix_service_request_proposals_customer_created
    ON service_request_proposals (customer_id, created_at DESC);

CREATE TABLE service_request_proposal_audit_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL
        REFERENCES service_request_proposals(request_id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES customers(id),
    event_type VARCHAR(20) NOT NULL,
    request_type VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_service_request_proposal_audit_events_type
        CHECK (event_type IN ('PROPOSED', 'CONFIRMED', 'CANCELLED', 'EXPIRED', 'CONFLICTED'))
);

CREATE INDEX ix_service_request_proposal_audit_request_time
    ON service_request_proposal_audit_events (request_id, occurred_at);

COMMIT;
